def _scale_bits(word: int, shift: int) -> int:
    """Exact binary32 power-of-two scaling; caller has established the bounds."""
    sign, exponent, fraction = word & 0x80000000, (word >> 23) & 255, word & 0x7fffff
    if exponent:
        target = exponent + shift
        if target > 0:
            return sign | (target << 23) | fraction
        return sign | ((0x800000 | fraction) >> (1 - target))
    fraction = fraction << shift if shift >= 0 else fraction >> -shift
    if fraction < 0x800000:
        return sign | fraction
    target = fraction.bit_length() - 23
    return sign | (target << 23) | ((fraction >> (target - 1)) & 0x7fffff)


def _literal(payload: bytes) -> str:
    # Adjacent string tokens become one object. Avoid one AST node per byte,
    # which makes multi-MiB initializer-list payloads expensive to compile.
    return '\n'.join('    "' + ''.join(f'\\x{x:02x}' for x in payload[i:i+64]) + '"'
                     for i in range(0, len(payload), 64))


def compile_model(data: bytes, symbol: str, channels: int, *, seed: int) -> CompiledModel:
    """Generate self-contained C99 and a private integration header.

    Input is little-endian, finite IEEE binary32, in complete row-major rows.
    Supported columns: 2..16. The seed is an integer in [0, 2**256).
    Per-column signed dyadic scales are selected only when all stored values
    remain exactly representable, including subnormals and signed zero.

    ``symbol_prepare(const float *, size_t, symbol_prepared *)`` is static
    inline in the private header. ``symbol_evaluate(size_t, const
    symbol_prepared *, double *)`` is the exported, noinline row dot kernel.
    Both return 0 on success and -1 for invalid arguments. A prepared context
    must be initialized successfully and remain unmodified before evaluation.

    Require normal IEEE round-to-nearest behavior, gradual underflow, and no
    fast-math/reassociation. Products are exact in binary64; column permutation
    can change summation rounding. No bit-identical output promise is made.
    """
    if not isinstance(data, (bytes, bytearray, memoryview)):
        raise ValueError('model input must be a byte buffer of little-endian f32 values')
    if not isinstance(symbol, str) or not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*', symbol) or symbol.startswith('binobf_'):
        raise ValueError('model symbol must be a C identifier starting with a letter and not binobf_')
    if not isinstance(channels, int) or isinstance(channels, bool) or not 2 <= channels <= 16:
        raise ValueError('channels must be an integer between 2 and 16')
    if not isinstance(seed, int) or isinstance(seed, bool) or not 0 <= seed < (1 << 256):
        raise ValueError('seed must be an integer between 0 and 2^256-1')
    data = bytes(data)
    if not data or len(data) > MAX_BYTES or len(data) % (4 * channels):
        raise ValueError('model must contain complete nonempty rows and be at most 64 MiB')

    words = array('I')
    if words.itemsize != 4:
        raise ValueError('this generator requires a 32-bit unsigned array type')
    words.frombytes(data)
    if sys.byteorder != 'little':
        words.byteswap()
    lower, upper = [-4] * channels, [4] * channels
    for index, word in enumerate(words):
        exponent, fraction = (word >> 23) & 255, word & 0x7fffff
        if exponent == 255:
            raise ValueError(f'non-finite f32 at value {index}')
        mantissa = fraction | (0x800000 if exponent else 0)
        if not mantissa:
            continue
        base = exponent - 150 if exponent else -149
        top = base + mantissa.bit_length() - 1
        bottom = base + (mantissa & -mantissa).bit_length() - 1
        column = index % channels
        lower[column] = max(lower[column], -149 - bottom)
        upper[column] = min(upper[column], 127 - top)

    digest = hashlib.sha256(b'binobf-model-v1\0' + seed.to_bytes(32, 'little')
                            + symbol.encode('ascii') + b'\0' + data).digest()
    rng = random.Random(int.from_bytes(digest, 'big'))
    order = list(range(channels)); rng.shuffle(order)
    if order == list(range(channels)):
        order = order[1:] + order[:1]
    shifts = []
    for column in order:
        choices = [k for k in range(lower[column], upper[column] + 1) if k]
        shifts.append(rng.choice(choices) if choices else 0)
    signs = [rng.randrange(2) for _ in order]
    if not any(signs):
        signs[0] = 1
    encoded = array('I')
    for row in range(0, len(words), channels):
        for physical, logical in enumerate(order):
            encoded.append(_scale_bits(words[row + logical], shifts[physical]) ^ (signs[physical] << 31))
    if sys.byteorder != 'little':
        encoded.byteswap()
    payload = encoded.tobytes()
    rows = len(words) // channels
    ident = 'bmodel_' + digest.hex()[:16]
    guard = ident.upper() + '_H'
    tag = int.from_bytes(digest[8:16], 'little') or 1
    prep = '\n'.join(f'    next.opaque_state[{j}] = checked[{logical}] * '
                     f'{((-1.0 if signs[j] else 1.0) * 2.0 ** -shifts[j]).hex()};'
                     for j, logical in enumerate(order))
    header = _LICENSE + f'''/* Private build header: contains the paired weight transformation.
   Reversible representation, not encryption. Basis queries recover numeric values.
   Build the generated source without LTO. Keep contexts model-specific.
   Numerical contract: IEEE round-to-nearest; preserve subnormals; no fast-math.
   Returns -1 without changing the destination for invalid arguments.
   Context tags detect accidental mixups, not tampering or unauthorized use. */
#ifndef {guard}
#define {guard}
#include <stddef.h>
#include <stdint.h>
#include <string.h>
#include <float.h>
#include <limits.h>
#if defined(__FAST_MATH__) || (defined(__FINITE_MATH_ONLY__) && __FINITE_MATH_ONLY__ > 0)
#error "binobf model requires non-fast-math floating point"
#endif
#if CHAR_BIT != 8 || FLT_RADIX != 2 || FLT_MANT_DIG != 24 || FLT_MAX_EXP != 128 || FLT_MIN_EXP != -125 || DBL_MANT_DIG != 53 || DBL_MAX_EXP != 1024 || DBL_MIN_EXP != -1021
#error "binobf model requires IEEE binary32 float and binary64 double"
#endif
typedef char {ident}_sizes[(sizeof(float) == 4 && sizeof(double) == 8) ? 1 : -1];
enum {{ {symbol}_rows = {rows}, {symbol}_channels = {channels} }};
typedef struct {{ uint64_t opaque_tag; double opaque_state[{channels}]; }} {symbol}_prepared;
#ifdef __cplusplus
extern "C" {{
#endif
static inline int {symbol}_prepare(const float *weights, size_t count, {symbol}_prepared *prepared) {{
    double checked[{channels}];
    {symbol}_prepared next;
    if (!weights || !prepared || count != (size_t){channels}) return -1;
    for (size_t i = 0; i < (size_t){channels}; ++i) {{
        uint32_t bits;
        float value;
        memcpy(&bits, weights + i, 4);
        if ((bits & UINT32_C(0x7f800000)) == UINT32_C(0x7f800000)) return -1;
        memcpy(&value, &bits, 4);
        checked[i] = (double)value;
    }}
{prep}
    next.opaque_tag = UINT64_C(0x{tag:016x});
    *prepared = next;
    return 0;
}}
/* Only successfully prepared, unmodified contexts are valid here. */
int {symbol}_evaluate(size_t row, const {symbol}_prepared *prepared, double *out);
#ifdef __cplusplus
}}
#endif
#endif
'''
    operations = '\n'.join(f'    sum += (double){ident}_load(p + {j * 4}u) * prepared->opaque_state[{j}];'
                           for j in range(channels))
    source = header + f'''
/* Self-contained generated implementation; no plaintext read/cache interface.
   The trailing C string terminator is not a model element. */
static const unsigned char {ident}_data[] =
{_literal(payload)};
static inline float {ident}_load(const unsigned char *p) {{
    uint32_t bits = (uint32_t)p[0] | ((uint32_t)p[1] << 8)
                  | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
    float value;
    memcpy(&value, &bits, 4);
    return value;
}}
#if defined(__GNUC__) || defined(__clang__)
__attribute__((noinline))
#endif
int {symbol}_evaluate(size_t row, const {symbol}_prepared *prepared, double *out) {{
    const unsigned char *p;
    double sum = 0.0;
    if (row >= (size_t){rows} || !prepared || !out || prepared->opaque_tag != UINT64_C(0x{tag:016x})) return -1;
    p = {ident}_data + row * {channels * 4}u;
{operations}
    *out = sum;
    return 0;
}}
'''
    return CompiledModel(source, header, {
        'input_bytes': len(data), 'stored_bytes': len(payload), 'c_string_terminator_bytes': 1,
        'rows': rows, 'channels': channels, 'encoding': 'signed-dyadic-column-permutation-f32',
        'accumulation': 'binary64', 'prepared_bytes': 8 * (channels + 1),
        'prepare_interface': 'static-inline-private-header', 'raw_read_api': False,
        'full_plaintext_runtime_cache': False, 'encryption': False,
        'basis_queries_recover_numeric_matrix': True, 'payload_and_kernel_reusable': True,
        'bit_identical_output_guaranteed': False,
        'error_bound': 'Under the numerical contract: gamma(channels-1) * sum(abs(exact f32 products)); gamma(k)=k*2^-53/(1-k*2^-53).',
    })
