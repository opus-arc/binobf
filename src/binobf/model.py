"""Compile finite f32 rows into a paired numeric representation and C dot kernel.

This is reversible representation diversification, not encryption. A caller
able to choose basis weights and observe each row can recover the matrix. The
transformed payload and consuming kernel can also be reused together. The API
avoids a generic plaintext reader and a full decoded-matrix runtime cache; it
does not establish a confidentiality or anti-reuse boundary.
"""
from __future__ import annotations

from array import array
from dataclasses import dataclass
import hashlib
import random
import re
import sys


MAX_BYTES = 64 * 1024 * 1024


@dataclass(frozen=True)
class CompiledModel:
    source: str
    header: str
    statistics: dict


