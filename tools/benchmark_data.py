#!/usr/bin/env python3
"""Measure standalone native data-reader cost, not whole-application overhead.

The legacy byte initializer is adapted to an equal C string only for this
benchmark; its reader and uint32 tables remain unchanged. Generator and adapter
times are recorded separately. No generated source or seed enters the report.
"""
import argparse
import codecs
import hashlib
import io
import json
import math
import os
from pathlib import Path
import platform
import random
import re
import shutil
import statistics
import subprocess
import sys
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
from binobf.assets import pack
from binobf.assets_diverse import pack_diverse

OCTAL = tuple(f'\\{i:03o}' for i in range(256))


def _check_output(output, source=None, force=False):
    if output is None:
        return
    path = Path(output)
    if source is not None:
        source = Path(source)
        if path.resolve() == source.resolve():
            raise ValueError('benchmark output must not replace the input')
        if path.exists() and source.exists() and os.path.samefile(path, source):
            raise ValueError('benchmark output is a hard link to the input')
    if path.is_dir():
        raise ValueError(f'benchmark output is a directory: {path}')
    if (path.exists() or path.is_symlink()) and not force:
        raise ValueError(f'benchmark output exists: {path}; use --force to replace it')
    if path.parent.exists() and not path.parent.is_dir():
        raise ValueError(f'benchmark output parent is not a directory: {path.parent}')


def _atomic_output(output, text, source=None, force=False):
    path = Path(output)
    _check_output(path, source, force)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix='.binobf-benchmark-', dir=path.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        # The benchmark can be long: reject aliases/new output collisions again.
        _check_output(path, source, force)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def literal(data):
    return '\n'.join('    "' + ''.join(OCTAL[b] for b in data[i:i + 64]) + '"'
                     for i in range(0, len(data), 64))


def adapt_legacy(source):
    """Replace only the generated byte initializer, checking its exact bytes."""
    declaration = re.search(r'^static const volatile unsigned char (\w+_bytes)\[\] = \{\n',
                            source, re.MULTILINE)
    if declaration is None:
        raise ValueError('legacy payload declaration not found')
    end = source.index('\n};', declaration.end()) + len('\n};')
    prefix, suffix = source[:declaration.start()], source[end:]
    old_hash, new_hash = hashlib.sha256(), hashlib.sha256()
    out, count = io.StringIO(), 0
    out.write(f'static const volatile unsigned char {declaration[1]}[] =\n')
    body = io.StringIO(source[declaration.end():end - len('\n};')])
    pattern = re.compile(r'\s*(?:0x[0-9a-f]{2}\s*,\s*)+\Z')
    for line in body:
        if not pattern.fullmatch(line):
            raise ValueError('unexpected legacy byte initializer syntax')
        payload = bytes.fromhex(line.replace('0x', '').replace(',', ''))
        old_hash.update(payload)
        escaped = ''.join(OCTAL[b] for b in payload)
        # Independently decode the emitted octal spelling before accepting it.
        recovered = codecs.decode(escaped, 'unicode_escape').encode('latin1')
        new_hash.update(recovered)
        count += len(payload)
        out.write('    "' + escaped + '"\n')
    out.write(';')
    replacement = out.getvalue()
    adapted = prefix + replacement + suffix
    unchanged = hashlib.sha256((prefix + suffix).encode()).hexdigest()
    actual = adapted[:len(prefix)] + adapted[len(prefix) + len(replacement):]
    if hashlib.sha256(actual.encode()).hexdigest() != unchanged or old_hash.digest() != new_hash.digest():
        raise AssertionError('legacy build adaptation changed data or reader code')
    return adapted, {
        'applied': True, 'change': 'byte initializer to equal fixed-width octal string',
        'payload_bytes': count, 'initializer_payload_sha256': old_hash.hexdigest(),
        'literal_payload_sha256': new_hash.hexdigest(), 'payload_equal': True,
        'non_array_source_sha256': unchanged, 'non_array_source_unchanged': True,
        'legacy_product_generator_changed': False, 'added_unused_terminator_bytes': 1}


CONTROL = '''#include <stddef.h>
#include <string.h>
static const unsigned char payload[] =
%s;
size_t control_size(void) { return (size_t)%d; }
int control_read(size_t offset, void *output, size_t length) {
    if (offset > (size_t)%d || length > (size_t)%d - offset || (length && !output)) return -1;
    if (length) memcpy(output, payload + offset, length);
    return 0;
}
'''

HARNESS = r'''#define _POSIX_C_SOURCE 200809L
#include <stdint.h>
#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#define ROUNDS @ROUNDS@
#define WARMUPS @WARMUPS@
#define TARGET_BYTES ((size_t)@TARGET_BYTES@)
typedef int (*reader_fn)(size_t, void *, size_t);
size_t control_size(void); size_t legacy_size(void); size_t diverse_size(void);
int control_read(size_t, void *, size_t);
int legacy_read(size_t, void *, size_t);
int diverse_read(size_t, void *, size_t);
static reader_fn readers[3] = {control_read, legacy_read, diverse_read};
static const char *names[3] = {"memcpy", "legacy", "diverse"};
static size_t offsets[1024];
static volatile uint64_t sink;
static double now(void) {
    struct timespec t;
    if (clock_gettime(CLOCK_MONOTONIC, &t)) exit(10);
    return (double)t.tv_sec + (double)t.tv_nsec * 1e-9;
}
static double measure(reader_fn fn, int mode, size_t size, size_t passes, size_t small, size_t calls) {
    unsigned char output[4096];
    int status = 0;
    const double start = now();
    if (!mode) {
        for (size_t repeat = 0; repeat < passes; ++repeat)
            for (size_t offset = 0; offset < size;) {
                size_t n = size - offset < sizeof(output) ? size - offset : sizeof(output);
                status |= fn(offset, output, n);
                offset += n;
            }
    } else {
        for (size_t i = 0; i < calls; ++i)
            status |= fn(offsets[i & 1023u], output, small);
    }
    const double elapsed = now() - start;
    if (status) exit(11);
    /* Calls cross translation units without LTO. Consume the last output after
       stopping the timer; hashing the full decoded data is not timed. */
    sink += output[0];
    return elapsed;
}
int main(void) {
    const size_t size = control_size();
    if (!size || legacy_size() != size || diverse_size() != size) return 2;
    const size_t passes = (TARGET_BYTES + size - 1u) / size;
    const size_t small = size < 32u ? size : 32u;
    const size_t calls = (TARGET_BYTES + small - 1u) / small;
    unsigned char expected[4096], decoded[4096];
    double verify_start = now();
    for (size_t offset = 0; offset < size;) {
        size_t n = size - offset < sizeof(expected) ? size - offset : sizeof(expected);
        if (control_read(offset, expected, n)) return 3;
        for (unsigned p = 1; p < 3; ++p)
            if (readers[p](offset, decoded, n) || memcmp(expected, decoded, n)) return 4;
        offset += n;
    }
    double verify_seconds = now() - verify_start;
    uint64_t schedule = UINT64_C(0x7bdf136ac03e9281);
    for (unsigned i = 0; i < 1024; ++i) {
        schedule = schedule * UINT64_C(6364136223846793005) + UINT64_C(1442695040888963407);
        offsets[i] = (size_t)(schedule % (uint64_t)(size - small + 1u));
        if (control_read(offsets[i], expected, small)) return 5;
        for (unsigned p = 1; p < 3; ++p)
            if (readers[p](offsets[i], decoded, small) || memcmp(expected, decoded, small)) return 6;
    }
    double times[2][3][ROUNDS];
    for (unsigned mode = 0; mode < 2; ++mode) {
        for (unsigned round = 0; round < WARMUPS; ++round)
            for (unsigned k = 0; k < 3; ++k)
                (void)measure(readers[(round + k) % 3u], (int)mode, size, passes, small, calls);
        for (unsigned round = 0; round < ROUNDS; ++round)
            for (unsigned k = 0; k < 3; ++k) {
                unsigned p = (round + k) % 3u;
                times[mode][p][round] = measure(readers[p], (int)mode, size, passes, small, calls);
            }
    }
    printf("{\"input_bytes\":%zu,\"full_validation_seconds\":%.9g,\"full_validation_equal\":true,", size, verify_seconds);
    printf("\"modes\":{");
    for (unsigned mode = 0; mode < 2; ++mode) {
        if (mode) printf(",");
        printf("\"%s\":{\"bytes_per_round\":%zu,\"calls_per_round\":%zu,\"samples_seconds\":{",
               mode ? "small_ranges" : "sequential_4096",
               mode ? calls * small : passes * size,
               mode ? calls : passes * ((size + 4095u) / 4096u));
        for (unsigned p = 0; p < 3; ++p) {
            if (p) printf(",");
            printf("\"%s\":[", names[p]);
            for (unsigned round = 0; round < ROUNDS; ++round) {
                if (round) printf(",");
                printf("%.12g", times[mode][p][round]);
            }
            printf("]");
        }
        printf("}}");
    }
    printf("},\"small_range_bytes\":%zu,\"sink\":%llu}\n", small, (unsigned long long)sink);
    return 0;
}
'''


def execute(command, *, timeout=180):
    start = time.monotonic()
    result = subprocess.run(command, text=True, capture_output=True, timeout=timeout)
    if result.returncode:
        raise RuntimeError(f'Command failed ({result.returncode}): {command!r}\n{result.stderr}')
    return result.stdout, time.monotonic() - start


def benchmark(args):
    # Reject a destructive report destination before reading data or compiling.
    _check_output(args.output, args.input, args.force)
    compiler = shutil.which(args.cc)
    if not compiler:
        raise ValueError(f'C compiler not found: {args.cc}')
    if args.input:
        path = Path(args.input)
        limit = 64 * 1024 * 1024
        with path.open('rb') as stream:
            data = stream.read(limit + 1)
        if len(data) > limit:
            raise ValueError('input exceeds the supported 64 MiB asset bound')
        input_kind = 'supplied-file'
    else:
        data = random.Random(417).randbytes(args.size)
        input_kind = 'deterministic-synthetic-bytes'
    if not data:
        raise ValueError('input must not be empty')
    timings, generated_metadata = {}, {}
    flags = ['-std=c99', '-O2', '-fno-lto', '-fvisibility=hidden']
    with tempfile.TemporaryDirectory(prefix='binobf-data-bench-') as temporary:
        directory = Path(temporary)
        start = time.monotonic()
        (directory / 'control.c').write_text(CONTROL % (literal(data), len(data), len(data), len(data)))
        timings['control_format_seconds'] = time.monotonic() - start
        start = time.monotonic()
        generated = pack(data, 'legacy', seed=args.seed, block_size=4096)
        timings['legacy_generator_seconds'] = time.monotonic() - start
        generated_metadata['legacy'] = generated.statistics
        start = time.monotonic()
        source, adaptation = adapt_legacy(generated.source)
        timings['legacy_build_adaptation_seconds'] = time.monotonic() - start
        (directory / 'legacy.c').write_text(source)
        del source, generated
        start = time.monotonic()
        generated = pack_diverse(data, 'diverse', seed=args.seed, block_size=4096)
        timings['diverse_generator_seconds'] = time.monotonic() - start
        generated_metadata['diverse'] = generated.statistics
        (directory / 'diverse.c').write_text(generated.source)
        del generated
        harness = HARNESS.replace('@ROUNDS@', str(args.rounds)).replace('@WARMUPS@', str(args.warmups))
        harness = harness.replace('@TARGET_BYTES@', str(args.bytes_per_round))
        (directory / 'harness.c').write_text(harness)
        for name in ('control', 'legacy', 'diverse', 'harness'):
            _, elapsed = execute([compiler, *flags, '-c', str(directory / (name + '.c')),
                                  '-o', str(directory / (name + '.o'))])
            timings[name + '_compile_seconds'] = elapsed
        executable = directory / 'probe'
        _, timings['link_seconds'] = execute([compiler, '-O2', '-fno-lto',
                                              *(str(directory / (n + '.o')) for n in
                                                ('control', 'legacy', 'diverse', 'harness')),
                                              '-o', str(executable)])
        stdout, timings['native_probe_seconds'] = execute([str(executable)])
        measured = json.loads(stdout)
    for mode in measured['modes'].values():
        samples = mode['samples_seconds']
        if any(not math.isfinite(t) or t <= 0 for values in samples.values() for t in values):
            raise RuntimeError('non-positive or invalid timing sample')
        medians = {name: statistics.median(values) for name, values in samples.items()}
        mode['median_seconds'] = medians
        mode['median_nanoseconds_per_byte'] = {
            name: elapsed * 1e9 / mode['bytes_per_round'] for name, elapsed in medians.items()}
        mode['ratio_of_median_times_to_memcpy'] = {name: elapsed / medians['memcpy']
                                                  for name, elapsed in medians.items()}
        mode['diverse_to_legacy_ratio_of_medians'] = medians['diverse'] / medians['legacy']
        mode['median_paired_ratios_to_memcpy'] = {
            name: statistics.median(t / baseline for t, baseline in zip(values, samples['memcpy']))
            for name, values in samples.items()}
    compiler_version, _ = execute([compiler, '--version'])
    result = {
        'schema': 'binobf-native-data-benchmark/v1',
        'scope': 'Standalone data range reads; not overall audio or application overhead',
        'limits': ['Host-specific CPU/cache/compiler results; no timing-security claim',
                   'Small ranges repeat 1024 precomputed offsets; this is not every working-set pattern',
                   'The supplied data reader remains reusable; speed is not evidence of confidentiality'],
        'platform': {'system': platform.system(), 'machine': platform.machine(),
                     'release': platform.release()},
        'compiler': {'path': compiler, 'version': compiler_version.splitlines()[0], 'flags': flags},
        'input': {'kind': input_kind, 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()},
        'method': {'rounds': args.rounds, 'warmups': args.warmups, 'block_size': 4096,
                   'order': 'Rotate memcpy/legacy/diverse order each paired round',
                   'translation_units': 'Separate control, legacy, diverse, harness; LTO disabled',
                   'verification': 'Full equality and all scheduled small reads before timing',
                   'timed_hashing': False, 'offset_schedule_entries': 1024,
                   'minimum_requested_bytes_per_round': args.bytes_per_round},
        'build_seconds': timings, 'legacy_build_adaptation': adaptation,
        'profile_statistics': generated_metadata, 'measurement': measured}
    text = json.dumps(result, indent=2) + '\n'
    if args.output:
        _atomic_output(args.output, text, args.input, args.force)
    print(text, end='')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', help='Optional complete input file, at most 64 MiB')
    parser.add_argument('--size', type=int, default=1024 * 1024 + 13, help='Synthetic input bytes')
    parser.add_argument('--seed', type=int, default=2026, help='Build diversity seed; not a secret')
    parser.add_argument('--rounds', type=int, default=9)
    parser.add_argument('--warmups', type=int, default=2)
    parser.add_argument('--bytes-per-round', type=int, default=32 * 1024 * 1024)
    parser.add_argument('--cc', default='cc')
    parser.add_argument('--output', help='Write the same JSON to this path')
    parser.add_argument('--force', action='store_true', help='Replace an existing report, never the input')
    args = parser.parse_args()
    if not (0 < args.size <= 64 * 1024 * 1024):
        parser.error('--size must be between 1 and 64 MiB')
    if not (3 <= args.rounds <= 99 and 1 <= args.warmups <= 20):
        parser.error('--rounds must be 3..99 and --warmups 1..20')
    if not (0 < args.bytes_per_round <= 1024 * 1024 * 1024):
        parser.error('--bytes-per-round must be between 1 byte and 1 GiB')
    try:
        benchmark(args)
    except (ValueError, OSError) as exc:
        parser.error(str(exc))


if __name__ == '__main__':
    main()
